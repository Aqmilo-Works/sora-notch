//! The macOS side of board (board.rs), its `os` module. Everything else there is shared.
//! The general pasteboard is read and written through AppKit (NSPasteboard). macOS sends no "clipboard changed" event,
//! so its change count is checked twice a second, the way clipboard managers on the Mac do.
#![allow(unused_imports, unused_unsafe)]
use super::*;
use objc2::rc::Retained;
use objc2_app_kit::{NSPasteboard, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF, NSWorkspace};
use objc2_foundation::{NSData, NSString};

/// The lines in a picture with their boxes (px, top-left origin), through Vision's text recognition in the languages
/// macOS detects. shortcut: word boxes are the line's box shared out by character count (Vision boxes lines); upgrade
/// with boundingBoxForRange when exact word picking matters.
pub(super) fn ocr_lines(img: &image::DynamicImage) -> Option<Vec<OcrLine>> {
    use objc2::AllocAnyThread;
    use objc2_foundation::{NSArray, NSDictionary};
    use objc2_vision::{VNImageRequestHandler, VNRecognizeTextRequest, VNRequest, VNRequestTextRecognitionLevel};
    let (w, h) = (img.width() as f32, img.height() as f32);
    let mut png = std::io::Cursor::new(Vec::new());
    img.write_to(&mut png, image::ImageFormat::Png).ok()?;
    let data = NSData::with_bytes(png.get_ref());
    let request = unsafe { VNRecognizeTextRequest::new() };
    unsafe {
        request.setRecognitionLevel(VNRequestTextRecognitionLevel::Accurate);
        request.setUsesLanguageCorrection(true);
        request.setAutomaticallyDetectsLanguage(true);
    }
    let handler = unsafe { VNImageRequestHandler::initWithData_options(VNImageRequestHandler::alloc(), &data, &NSDictionary::new()) };
    let r: &VNRequest = &request;
    unsafe { handler.performRequests_error(&NSArray::from_slice(&[r])) }.ok()?;
    let mut out = Vec::new();
    for obs in unsafe { request.results() }?.iter() {
        let Some(best) = unsafe { obs.topCandidates(1) }.firstObject() else { continue };
        let text = unsafe { best.string() }.to_string();
        if text.trim().is_empty() { continue; }
        let b = unsafe { obs.boundingBox() };
        let (x, y, bw, bh) = (b.origin.x as f32 * w, (1.0 - b.origin.y as f32 - b.size.height as f32) * h, b.size.width as f32 * w, b.size.height as f32 * h);
        out.push(OcrLine { words: word_boxes(&text, x, y, bw, bh), text });
    }
    Some(out)
}
/// A line's words with their boxes shared out by character count (pure; tested).
pub(super) fn word_boxes(text: &str, x: f32, y: f32, w: f32, h: f32) -> Vec<OcrWord> {
    let chars: Vec<char> = text.chars().collect();
    let total = chars.len().max(1) as f32;
    let mut words = Vec::new();
    let mut i = 0;
    while i < chars.len() {
        if chars[i].is_whitespace() { i += 1; continue; }
        let start = i;
        while i < chars.len() && !chars[i].is_whitespace() { i += 1; }
        words.push(OcrWord { text: chars[start..i].iter().collect(), x: x + w * start as f32 / total, y, w: w * (i - start) as f32 / total, h });
    }
    words
}

fn general() -> Retained<NSPasteboard> { unsafe { NSPasteboard::generalPasteboard() } }
/// Password managers mark what must not be kept (the nspasteboard.org convention: concealed, transient, auto-generated).
fn excluded(pb: &NSPasteboard) -> bool {
    const MARKS: [&str; 3] = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
    unsafe { pb.types() }.is_some_and(|types| types.iter().any(|t| MARKS.contains(&t.to_string().as_str())))
}
fn text_of(pb: &NSPasteboard) -> Option<String> { unsafe { pb.stringForType(NSPasteboardTypeString) }.map(|s| s.to_string()) }
fn picture_of(pb: &NSPasteboard) -> Option<image::DynamicImage> {
    for (kind, format) in unsafe { [(NSPasteboardTypePNG, image::ImageFormat::Png), (NSPasteboardTypeTIFF, image::ImageFormat::Tiff)] } {
        if let Some(data) = unsafe { pb.dataForType(kind) } {
            if let Ok(img) = image::load_from_memory_with_format(&data.to_vec(), format) { return Some(img); }
        }
    }
    None
}
/// (name, path) of the app a copy came from: the app in front (macOS does not say who wrote the pasteboard).
fn source() -> (String, String) {
    let Some(app) = (unsafe { NSWorkspace::sharedWorkspace().frontmostApplication() }) else { return Default::default() };
    if unsafe { app.processIdentifier() } as u32 == std::process::id() { return Default::default(); }
    let name = unsafe { app.localizedName() }.map(|n| n.to_string()).unwrap_or_default();
    let path = unsafe { app.bundleURL() }.and_then(|u| unsafe { u.path() }).map(|p| p.to_string()).unwrap_or_default();
    (name, path)
}
fn capture() {
    if now_ms() < SKIP_UNTIL.load(Ordering::SeqCst) { return; }
    if with(|s| s.capture.unwrap_or(true)) != Some(true) { return; }
    let pb = general();
    if excluded(&pb) { return; }
    if let Some(text) = text_of(&pb) { add_text(text, source()); } else if let Some(img) = picture_of(&pb) { add_image(img, source()); }
}
pub(super) fn listen() {
    let mut seen = unsafe { general().changeCount() };
    loop {
        thread::sleep(std::time::Duration::from_millis(500));
        let now = unsafe { general().changeCount() };
        // A short wait, as on Windows, so the app still writing the pasteboard (several types) is done.
        if now != seen { thread::sleep(std::time::Duration::from_millis(120)); capture(); seen = unsafe { general().changeCount() }; }
    }
}
fn put(write: impl FnOnce(&NSPasteboard) -> bool) -> AppResult<()> {
    SKIP_UNTIL.store(now_ms() + 1500, Ordering::SeqCst);
    let pb = general();
    unsafe { pb.clearContents() };
    if write(&pb) { Ok(()) } else { Err("The clipboard is busy. Try again.".into()) }
}
fn put_text(text: &str) -> AppResult<()> { put(|pb| unsafe { pb.setString_forType(&NSString::from_str(text), NSPasteboardTypeString) }) }
/// The text on the clipboard now: read here, so the page never asks macOS for clipboard access.
#[tauri::command]
pub fn board_clip_text() -> Option<String> { text_of(&general()).map(|t| t.trim().chars().take(2048).collect()) }
/// Puts some text on the clipboard (a chat message copied from the history); the board does not take it as a new copy.
#[tauri::command]
pub fn board_put_text(text: String) -> AppResult<()> { put_text(&text.chars().take(MAX_TEXT).collect::<String>()) }
/// Puts the item back on the clipboard (text as text, a picture as PNG).
#[tauri::command]
pub fn board_copy(id: String) -> AppResult<()> {
    let item = with(|s| s.items.iter().find(|i| i.id == id).cloned()).flatten().ok_or("That item is gone.")?;
    if item.kind == "image" {
        let (png, _) = files(&id).ok_or("No picture.")?;
        let bytes = fs::read(&png).map_err(err)?;
        put(|pb| unsafe { pb.setData_forType(Some(&NSData::with_bytes(&bytes)), NSPasteboardTypePNG) })
    } else {
        put_text(&item.text)
    }
}

#[cfg(test)]
mod mac_tests {
    #[test]
    fn words_share_the_line() {
        let w = super::word_boxes("ab  cd", 0.0, 5.0, 60.0, 10.0);
        assert_eq!(w.iter().map(|w| (w.text.as_str(), w.x, w.w)).collect::<Vec<_>>(), vec![("ab", 0.0, 20.0), ("cd", 40.0, 20.0)]);
    }
}
