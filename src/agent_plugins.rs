//! The plugins Sora writes for the agents that load code instead of running hook commands (OpenCode, Amp, Hermes).
//! Each one starts `sora.exe --hook --agent <name>` with the event as JSON on stdin, fire-and-forget, so the agent never
//! waits on Sora and nothing happens while Sora is closed. Only OpenCode's `permission.ask` waits for the notch's Allow /
//! Deny, and falls back to OpenCode's own prompt when nobody clicks.
//!
//! Ported from Coucou's plugins (github.com/louis-cfm/coucou, MIT, Copyright (c) 2026 Louis Raillé; see
//! THIRD-PARTY-NOTICES.md). Sora's versions also hand the tool's input to the "after" event, so file changes show.

/// Every plugin file Sora writes says so; only such a file is ever replaced or removed.
pub const MARK: &str = "generated by Sora";

/// `{HOOK}` is the path of sora.exe as a JSON string (also valid JavaScript, TypeScript and Python).
pub const OPENCODE: &str = r#"// Sora plugin for OpenCode, generated by Sora.
// Session and tool events go to Sora (sora.exe --hook), fire-and-forget: OpenCode never waits on them.
// permission.ask waits for the notch's Allow / Deny click and falls back to OpenCode's own prompt.
import { spawn } from 'node:child_process';

const HOOK = {HOOK};
const EVENT_MAP = {
  'session.created': 'SessionStart',
  'session.idle': 'Stop',
  'session.error': 'StopFailure',
  'session.deleted': 'SessionEnd',
  'session.execution.started': 'UserPromptSubmit',
  'session.execution.succeeded': 'Stop',
  'session.execution.failed': 'StopFailure',
};
const ARGS = new Map();

function forward(hook_event_name, payload) {
  try {
    const p = spawn(HOOK, ['--hook', '--agent', 'opencode'], { stdio: ['pipe', 'ignore', 'ignore'], detached: process.platform !== 'win32', windowsHide: true });
    p.on('error', () => {});
    p.stdin.on('error', () => {});
    p.stdin.end(JSON.stringify({ hook_event_name, ...payload }) + '\n');
    p.unref();
  } catch {}
}

function parseDecision(out) {
  try {
    const behavior = JSON.parse(out)?.hookSpecificOutput?.decision?.behavior;
    if (behavior === 'allow' || behavior === 'deny') return behavior;
  } catch {}
  return null;
}

function permissionReply(permission, directory) {
  return new Promise((resolve) => {
    let p, out = '', settled = false;
    const done = (status) => { if (!settled) { settled = true; resolve(status); } };
    try { p = spawn(HOOK, ['--hook', '--agent', 'opencode'], { stdio: ['pipe', 'pipe', 'ignore'], windowsHide: true }); } catch { resolve('ask'); return; }
    p.on('error', () => done('ask'));
    p.stdout.on('data', (chunk) => { out += chunk.toString(); if (out.includes('\n')) done(parseDecision(out) ?? 'ask'); });
    p.on('exit', () => done(parseDecision(out) ?? 'ask'));
    setTimeout(() => done('ask'), 115000);
    p.stdin.on('error', () => {});
    p.stdin.end(JSON.stringify({
      hook_event_name: 'PermissionRequest',
      session_id: permission?.sessionID || '',
      cwd: directory || '',
      tool_name: typeof permission?.type === 'string' ? permission.type : '',
      tool_input: permission?.metadata ?? null,
    }) + '\n');
  });
}

export const SoraPlugin = async ({ directory } = {}) => ({
  event: async ({ event }) => {
    const hook_event_name = EVENT_MAP[event?.type];
    if (!hook_event_name) return;
    const props = event?.properties || {};
    forward(hook_event_name, { session_id: props.sessionID || props.info?.id || '', cwd: directory || '' });
  },
  'tool.execute.before': async (input, output) => {
    if (input?.callID) ARGS.set(input.callID, output?.args ?? null);
    forward('PreToolUse', { session_id: input?.sessionID || '', cwd: directory || '', tool_name: typeof input?.tool === 'string' ? input.tool : '', tool_input: output?.args ?? null });
  },
  'tool.execute.after': async (input) => {
    const args = ARGS.get(input?.callID) ?? null;
    ARGS.delete(input?.callID);
    forward('PostToolUse', { session_id: input?.sessionID || '', cwd: directory || '', tool_name: typeof input?.tool === 'string' ? input.tool : '', tool_input: args });
  },
  'permission.ask': async (input, output) => { output.status = await permissionReply(input, directory); },
});

export default SoraPlugin;
"#;

pub const AMP: &str = r#"// Sora plugin for Amp, generated by Sora.
// Forwards Amp's events to Sora (sora.exe --hook), fire-and-forget and display only: it never decides anything for Amp.
import { spawn } from 'node:child_process';

const HOOK = {HOOK};

function forward(hook_event_name: string, fields: Record<string, unknown>): void {
  try {
    const p = spawn(HOOK, ['--hook', '--agent', 'amp'], { stdio: ['pipe', 'ignore', 'ignore'], detached: process.platform !== 'win32', windowsHide: true });
    p.on('error', () => {});
    p.stdin?.on('error', () => {});
    p.stdin?.end(JSON.stringify({ hook_event_name, ...fields }) + '\n');
    p.unref();
  } catch {}
}

export default function (amp: any): void {
  const session = (e: any) => ({ session_id: e?.thread?.id ?? '' });
  amp.on('session.start', (e: any) => { forward('SessionStart', session(e)); });
  amp.on('agent.start', (e: any) => { forward('UserPromptSubmit', { ...session(e), prompt: typeof e?.message === 'string' ? e.message : '' }); });
  // A step per tool once it has run (tool.call would need a verdict, and Sora never gives one), then its file change.
  amp.on('tool.result', (e: any) => {
    const tool = { ...session(e), tool_name: typeof e?.tool === 'string' ? e.tool : '', tool_input: e?.input ?? null };
    forward('PreToolUse', tool);
    forward('PostToolUse', tool);
  });
  amp.on('agent.end', (e: any) => { forward('Stop', { ...session(e), status: e?.status ?? '' }); });
}
"#;

pub const HERMES: &str = r#"# Sora plugin for Hermes Agent, generated by Sora.
# Session and tool events go to Sora (sora.exe --hook), fire-and-forget: Hermes keeps every approval to itself.
import json, os, subprocess, threading

HOOK = {HOOK}
_current_session_id = ''


def _fire(fields):
    def _run():
        try:
            extra = {'start_new_session': True} if os.name != 'nt' else {'creationflags': getattr(subprocess, 'CREATE_NO_WINDOW', 0)}
            p = subprocess.Popen([HOOK, '--hook', '--agent', 'hermes'], stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **extra)
            p.stdin.write(json.dumps(fields).encode() + b'\n')
            p.stdin.close()
            p.wait(timeout=5)
        except Exception:
            pass
    threading.Thread(target=_run, daemon=True).start()


def register(ctx):
    def on_session_start(**kwargs):
        global _current_session_id
        _current_session_id = kwargs.get('session_id', '')
        _fire({'hook_event_name': 'SessionStart', 'session_id': _current_session_id})

    def on_session_end(**kwargs):
        if kwargs.get('interrupted'):
            _fire({'hook_event_name': 'StopFailure', 'session_id': kwargs.get('session_id', '')})

    def post_llm_call(**kwargs):
        _fire({'hook_event_name': 'Stop', 'session_id': kwargs.get('session_id', '') or _current_session_id, 'last_assistant_message': kwargs.get('assistant_response', '')})

    def pre_tool_call(**kwargs):
        _fire({'hook_event_name': 'PreToolUse', 'session_id': kwargs.get('session_id', '') or _current_session_id, 'tool_name': kwargs.get('tool_name', ''), 'tool_input': kwargs.get('args') or {}})

    def post_tool_call(**kwargs):
        _fire({'hook_event_name': 'PostToolUse', 'session_id': kwargs.get('session_id', '') or _current_session_id, 'tool_name': kwargs.get('tool_name', ''), 'tool_input': kwargs.get('args') or {}})

    def pre_approval_request(**kwargs):
        # Observer only: Hermes asks and decides; the notch just says so.
        _fire({'hook_event_name': 'PreToolUse', 'session_id': kwargs.get('session_key', '') or _current_session_id, 'tool_name': 'HermesApproval', 'tool_input': {'command': kwargs.get('command', ''), 'description': kwargs.get('description', '')}})

    ctx.register_hook('on_session_start', on_session_start)
    ctx.register_hook('on_session_end', on_session_end)
    ctx.register_hook('post_llm_call', post_llm_call)
    ctx.register_hook('pre_tool_call', pre_tool_call)
    ctx.register_hook('post_tool_call', post_tool_call)
    ctx.register_hook('pre_approval_request', pre_approval_request)
"#;

pub const HERMES_YAML: &str = "name: sora\nversion: \"1.0\"\ndescription: Sora notch integration, generated by Sora\n";

/// The files of one agent's plugin under `home`, with `exe` filled in.
pub fn files(agent: &str, home: &std::path::Path, exe: &str) -> Vec<(std::path::PathBuf, String)> {
    let hook = serde_json::to_string(exe).unwrap_or_default();
    let fill = |t: &str| t.replace("{HOOK}", &hook);
    match agent {
        "opencode" => vec![(home.join(".config").join("opencode").join("plugins").join("sora.js"), fill(OPENCODE))],
        "amp" => vec![(home.join(".config").join("amp").join("plugins").join("sora.ts"), fill(AMP))],
        "hermes" => {
            let dir = home.join(".hermes").join("plugins").join("sora");
            vec![(dir.join("__init__.py"), fill(HERMES)), (dir.join("plugin.yaml"), HERMES_YAML.to_string())]
        }
        _ => vec![],
    }
}
